const lockBtn = document.getElementById("lockBtn");
let nLocked = false;

const boardEl = document.getElementById("board");
const nRange = document.getElementById("nRange");
const nValue = document.getElementById("nValue");
const stepBtn = document.getElementById("stepBtn");
const solveBtn = document.getElementById("solveBtn");
const stopBtn = document.getElementById("stopBtn");
const resetBtn = document.getElementById("resetBtn");
const statusEl = document.getElementById("status");

let N = parseInt(nRange.value, 10);
let userBoard = [];        // 2D: 1 if queen placed manually or by solver
let hasUnsafeConflict = false;

// Solver action list (generated by backtracking)
let actions = [];         // each action: {type: 'place'|'remove', row, col, auto: true}
let actionIndex = 0;
let solverInterval = null;
const STEP_MS = 150;      // fixed animation speed (ms) for Solve & Animate

nValue.textContent = N;

// ========== Board Build ==========
function buildBoard(n) {
  boardEl.innerHTML = "";
  userBoard = Array.from({ length: n }, () => Array(n).fill(0));
  boardEl.style.gridTemplateColumns = `repeat(${n}, 44px)`;
  boardEl.style.gridTemplateRows = `repeat(${n}, 44px)`;

  for (let r = 0; r < n; r++) {
    for (let c = 0; c < n; c++) {
      const cell = document.createElement("div");
      cell.className = "cell " + ((r + c) % 2 === 0 ? "light" : "dark");
      cell.dataset.r = r;
      cell.dataset.c = c;
      cell.addEventListener("click", () => toggleQueen(r, c));
      boardEl.appendChild(cell);
    }
  }
  statusEl.textContent = "Status: ready";
}

buildBoard(N);

nRange.oninput = () => {
  N = parseInt(nRange.value, 10);
  nValue.textContent = N;
  clearAllSolverState();
  buildBoard(N);
};

// ========== Helpers for conflicts & marking ==========
function findConflicts(row, col) {
  const res = [];
  for (let i = 0; i < N; i++) {
    if (userBoard[row][i] === 1 && i !== col) res.push([row, i]);
    if (userBoard[i][col] === 1 && i !== row) res.push([i, col]);
  }
  for (let i = -N; i <= N; i++) {
    let r1 = row + i, c1 = col + i;
    let r2 = row + i, c2 = col - i;
    if (r1 >= 0 && r1 < N && c1 >= 0 && c1 < N)
      if (userBoard[r1][c1] === 1 && !(r1 === row && c1 === col)) res.push([r1, c1]);
    if (r2 >= 0 && r2 < N && c2 >= 0 && c2 < N)
      if (userBoard[r2][c2] === 1 && !(r2 === row && c2 === col)) res.push([r2, c2]);
  }
  return res;
}

function areManualPlacementsClean() {
  // returns true if no manual conflict exists
  for (let r = 0; r < N; r++) {
    for (let c = 0; c < N; c++) {
      if (userBoard[r][c] === 1) {
        const conf = findConflicts(r, c);
        if (conf.length > 0) return false;
      }
    }
  }
  return true;
}

function markQueenAndLineRed(r1, c1, r2, c2) {
  // mark both queens red and mark intermediate cells red (persist until removal)
  const cell1 = boardEl.children[r1 * N + c1];
  const cell2 = boardEl.children[r2 * N + c2];
  cell1.classList.add("queen-danger");
  cell2.classList.add("queen-danger");

  let dr = (r2 > r1) ? 1 : (r2 < r1 ? -1 : 0);
  let dc = (c2 > c1) ? 1 : (c2 < c1 ? -1 : 0);
  let rr = r1 + dr, cc = c1 + dc;
  while (!(rr === r2 && cc === c2)) {
    boardEl.children[rr * N + cc].classList.add("danger-line");
    rr += dr; cc += dc;
  }
}

function clearDangerMarks() {
  [...boardEl.children].forEach(el => {
    el.classList.remove("queen-danger");
    el.classList.remove("danger-line");
  });
}

// ========== Manual toggle queen ==========
function toggleQueen(r, c) {
  // block manual placement if unsafe conflict exists
  if (hasUnsafeConflict && userBoard[r][c] === 0) {
    statusEl.textContent = "⚠ Resolve unsafe queens first!";
    return;
  }

  const idx = r * N + c;
  const cell = boardEl.children[idx];

  // remove queen if present
  if (userBoard[r][c] === 1) {
    userBoard[r][c] = 0;
    cell.classList.remove("q");
    cell.textContent = "";
    // clearing any danger marks globally (we remove all — if user wants persistent multiple conflicts, you can refine)
    clearDangerMarks();
    hasUnsafeConflict = false;
    statusEl.textContent = "Queen removed";
    // If actions were generated earlier, they become stale — clear
    actions = []; actionIndex = 0;
    stopSolverInterval();
    return;
  }

  // place queen
  userBoard[r][c] = 1;
  cell.classList.add("q");
  cell.textContent = "Q";

  // detect conflict: still allow placement but show red and block further placements
  const conflicts = findConflicts(r, c);
  if (conflicts.length > 0) {
    hasUnsafeConflict = true;
    statusEl.textContent = "⚠ Unsafe queen! Resolve to continue.";
    conflicts.forEach(([rr, cc]) => {
      markQueenAndLineRed(r, c, rr, cc);
    });
    // once unsafe, any previously generated solver actions are irrelevant
    actions = []; actionIndex = 0;
    stopSolverInterval();
  } else {
    statusEl.textContent = "Queen placed (safe)";

if (checkWin()) {
  showWinMessage();
  statusEl.textContent = "🎉 Puzzle Solved!";
}

  }
}

// ========== Solver action generator (backtracking from current manual state) ==========
// Will generate actions that only place/remove auto queens (auto: true)
// Pre-existing manual queens are respected (skipped) — but must be conflict-free.

function generateBacktrackingActions() {
  actions = [];
  actionIndex = 0;

  // Build initial pos array and occupancy masks from manual placements
  const pos = Array(N).fill(-1);
  const cols = Array(N).fill(false);
  const diag1 = Array(2 * N).fill(false);
  const diag2 = Array(2 * N).fill(false);
  const fixedRow = Array(N).fill(false);

  for (let r = 0; r < N; r++) {
    for (let c = 0; c < N; c++) {
      if (userBoard[r][c] === 1) {
        pos[r] = c;
        fixedRow[r] = true;
        cols[c] = true;
        diag1[r + c] = true;
        diag2[r - c + N] = true;
      }
    }
  }

  // quick check: if manual placements conflict -> do not generate
  for (let r = 0; r < N; r++) {
    if (pos[r] !== -1) {
      const c = pos[r];
      // if conflict with another fixed row -> return false
      for (let rr = 0; rr < N; rr++) {
        if (rr === r) continue;
        if (pos[rr] === -1) continue;
        const cc = pos[rr];
        if (cc === c || Math.abs(cc - c) === Math.abs(rr - r)) {
          // conflict found
          return false;
        }
      }
    }
  }

  let found = false;

  // Backtracking that records actions for auto placements only
  function dfs(row) {
    if (row === N) {
      found = true;
      return true;
    }

    if (fixedRow[row]) {
      // row already has a manual queen; move to next
      return dfs(row + 1);
    }

    for (let c = 0; c < N; c++) {
      if (cols[c] || diag1[row + c] || diag2[row - c + N]) continue;
      // record place action
      actions.push({ type: "place", row: row, col: c, auto: true });
      pos[row] = c;
      cols[c] = diag1[row + c] = diag2[row - c + N] = true;

      if (dfs(row + 1)) return true;

      // backtrack (record remove)
      actions.push({ type: "remove", row: row, col: c, auto: true });
      pos[row] = -1;
      cols[c] = diag1[row + c] = diag2[row - c + N] = false;
    }
    return false;
  }

    const ok = dfs(0);
    // return whether a solution was found. It's valid for a solution to require
    // zero auto actions (e.g. board already contains a complete valid solution),
    // so just return `ok` and let callers handle the empty-actions case.
    return ok;
}

// ========== Rendering actions ==========
function renderAction(act) {
  const idx = act.row * N + act.col;
  const cell = boardEl.children[idx];

  if (act.type === "place") {
    // guard: if there is already a manual queen at this cell, skip (shouldn't happen)
    if (userBoard[act.row][act.col] === 1 && act.auto) return;
    userBoard[act.row][act.col] = 1;
    cell.classList.add("q");
    cell.textContent = "Q";
    if (checkWin()) {
  showWinMessage();
  statusEl.textContent = "🎉 Puzzle Solved!";
}

  } else if (act.type === "remove") {
    // only remove auto-placed queens
    if (!act.auto) return;
    if (userBoard[act.row][act.col] === 1) {
      userBoard[act.row][act.col] = 0;
      cell.classList.remove("q");
      cell.textContent = "";
    }
  }
}

// ========== Step (single action) ==========
function stepOnce() {
  // if there is an existing unsafe conflict, block stepping
  if (hasUnsafeConflict) {
    statusEl.textContent = "⚠ Resolve unsafe queens first!";
    return;
  }

  // generate actions if needed
  if (actions.length === 0 || actionIndex >= actions.length) {
    const ok = generateBacktrackingActions();
    if (!ok) {
      statusEl.textContent = "No solution found (from current board) or manual conflicts exist.";
      return;
    }
    if (actions.length === 0) {
      statusEl.textContent = "Already solved or no auto moves needed.";
      return;
    }
    statusEl.textContent = "Solver actions generated — stepping.";
    actionIndex = 0;
  }

  const act = actions[actionIndex++];
  renderAction(act);

  // if placing created a conflict with manual queens (shouldn't for correct backtracking), mark it
  // but backtracking generator respects manual queens so this should be safe.

  // if finished
  if (actionIndex >= actions.length) {
    statusEl.textContent = "Solver finished (you can Step again to regenerate next solution if available).";
  } else {
    statusEl.textContent = `Step ${actionIndex}/${actions.length}`;
  }
}
function increaseBoardSize() {
    // Increase N by +1 until max size (14)
    if (N < 14) {
        N++;
        nRange.value = N;
        nValue.textContent = N;

        clearAllSolverState();
        clearDangerMarks();
        buildBoard(N);

        statusEl.textContent = `New Level: Solve N = ${N}`;
    } else {
        statusEl.textContent = "🎉 You completed ALL levels!";
    }

    // Hide win popup when new board loads
    const winBox = document.getElementById("winMessage");
    winBox.style.display = "none";
}

function checkWin() {
  // 1) Number of queens must equal N
  let qCount = 0;
  for (let r = 0; r < N; r++) {
    for (let c = 0; c < N; c++) {
      if (userBoard[r][c] === 1) qCount++;
    }
  }
  if (qCount !== N) return false;

  // 2) No unsafe conflicts
  for (let r = 0; r < N; r++) {
    for (let c = 0; c < N; c++) {
      if (userBoard[r][c] === 1) {
        const conf = findConflicts(r, c);
        if (conf.length > 0) return false;
      }
    }
  }
// Auto-increase N when solved (only if not locked)
if (!nLocked) {
    setTimeout(() => {
        increaseBoardSize();
    }, 800);  // small delay so user can see win message
}

  return true;
}

function showWinMessage() {
  const winBox = document.getElementById("winMessage");
  winBox.style.display = "block";   // show indefinitely
}


// ========== Solve & Animate ==========
function solveAndAnimate() {
  // block if unsafe conflict exists
  if (hasUnsafeConflict) {
    statusEl.textContent = "⚠ Resolve unsafe queens first!";
    return;
  }

  // generate actions (if not already)
  if (actions.length === 0 || actionIndex >= actions.length) {
    const ok = generateBacktrackingActions();
    if (!ok) {
      statusEl.textContent = "No solution found (from current board) or manual conflicts exist.";
      return;
    }
    if (actions.length === 0) {
      statusEl.textContent = "Already solved — nothing to animate.";
      return;
    }
    actionIndex = 0;
  }

  // start interval if not already running
  if (solverInterval) return;
  solverInterval = setInterval(() => {
    if (actionIndex >= actions.length) {
      stopSolverInterval();
      statusEl.textContent = "Solve finished";
      return;
    }
    const act = actions[actionIndex++];
    renderAction(act);
    statusEl.textContent = `Animating: ${actionIndex}/${actions.length}`;
  }, STEP_MS);

  solveBtn.disabled = true;
  stopBtn.disabled = false;
  stepBtn.disabled = true;
}

function stopSolverInterval() {
  if (solverInterval) {
    clearInterval(solverInterval);
    solverInterval = null;
  }
  solveBtn.disabled = false;
  stopBtn.disabled = true;
  stepBtn.disabled = false;
}

// ========== Reset ==========
function clearAllSolverState() {
  actions = [];
  actionIndex = 0;
  stopSolverInterval();
  hasUnsafeConflict = false;
  clearDangerMarks();
  statusEl.textContent = "Reset";
}

